-- =====================================================================
-- عمودُ خيارات الطباعة لأوراق العمل
-- ---------------------------------------------------------------------
-- الاختبارُ يحمل `settings` منذ بُني: خانةُ الاسم والتاريخ والترويسة وما
-- إليها. وورقةُ العمل لم تحمل شيئاً، لأنها لم تُطبع إلا بخياراتٍ ثابتةٍ
-- مكتوبةٍ في `print-exam.js`.
--
-- ثمّ طلب المعلّم أن يكتب تاريخَ الورقة كما يكتب تاريخ الاختبار
-- (٢٢ أغسطس ٢٠٢٦: «أوراق العمل بعد خل فيها تواريخ»)، فاحتاجت موضعاً
-- يُحفظ فيه. وعمودٌ باسم `settings` كنظيره في `exams` أولى من عمودٍ
-- واحدٍ للتاريخ: ما يأتي من خياراتٍ لاحقاً يسكنه بلا ترحيلٍ جديد.
--
-- والعمودُ له قيمةٌ افتراضيّة، فالأوراقُ المحفوظةُ قبل اليوم تبقى صالحةً
-- كما هي.
-- =====================================================================

alter table public.worksheets
    add column if not exists settings jsonb not null default '{}'::jsonb;
