-- ==========================================================================
-- إنزالُ الكتاب لا يُلغيه صاحبُه
-- ==========================================================================
-- حين يصل طلبُ إزالةٍ من الوزارة أو ناشر، يُنزَل الكتاب من لوحة التحكّم
-- (مسارُ TAKEDOWN.md): `is_taken_down = true` — فتُخفيه سياسةُ القراءة عن
-- صاحبه فوراً.
--
-- **لكنّ سياسةَ التعديل لا تشترط إلا أن يكون الصفُّ صفَّه.** فالمعلّم
-- الذي أُنزل كتابُه يستطيع بنداءٍ واحدٍ مباشرٍ للـAPI أن يعيده:
--     PATCH /rest/v1/books?id=eq.<id>   {"is_taken_down": false}
-- ومعرّفُ الكتاب في جهازه أصلاً (المخبأ المحلّي) فلا يحتاج تخميناً. وأسوأ
-- من عودة الكتاب أن `taken_down_reason` و`taken_down_at` يُمحيان معه —
-- أي **الورقةُ التي تُثبت أنك استجبت للطلب**.
--
-- والحلُّ مُشغِّلٌ يُعيد الأعمدةَ الثلاثة إلى قيمها القديمة إن جاء التعديل
-- من دور الـAPI. لا يرفع خطأً ولا يردّ الحفظ — يتجاهل ما لا يخصّ العميل
-- ويمضي.
--
-- ── لماذا لا يكسر شيئاً ──
-- • التطبيقُ لا يذكر هذه الأعمدة الثلاثة **ولا مرّةً واحدة** (فُحص كلُّ
--   ملفٍّ في teacher_app). فهو يرسلها ضمن الصفّ كما قرأها، ويستقبلها كما
--   هي — لا يقرأها ولا يعرضها ولا يقرّر بها شيئاً.
-- • ولأن المُشغِّل **يُصلح** القيمة ولا يرفع استثناءً، فأسوأُ ما يحدث لصفٍّ
--   يحاول تغييرها أن يُحفظ سليماً بالقيمة القديمة. لا رسالةَ خطأ، ولا
--   حفظٌ مردود، ولا زرٌّ يبدو ميّتاً.
-- • ولا يمسّ الإدراج: كتابٌ جديدٌ يُرفع كما كان.
--
-- ── ومن يُنزل ومن يُعيد إذن؟ ──
-- أنت من اللوحة (`postgres`) أو بمفتاح الخدمة (`service_role`) — وهما
-- خارجُ الشرط، فمسارُ TAKEDOWN.md يعمل كما هو، **وبندُ «إعادةُ كتابٍ أُنزل
-- بالخطأ» فيه يعمل كذلك**.
--
-- ── ما لا يُغلقه هذا الترحيل (بقصد) ──
-- الحذف. يستطيع المعلّم أن يحذف صفَّ الكتاب كلَّه فيزول معه أثرُ الإنزال.
-- ومنعُ الحذف كان **سيكسر شيئين خطيرين**: حذفُ الفصل يتتالى إلى كتبه،
-- وحذفُ الحساب (شرطُ آبل) يتتالى إلى كلّ شيء — فأيُّ استثناءٍ هنا يُفشل
-- العمليّتين. وعلاجُه الصحيح جدولُ سجلٍّ منفصلٌ لا يملكه المعلّم، وهو
-- قرارٌ مستقلّ.
--
-- ── الرجوع ──
--   drop trigger  if exists books_preserve_takedown on public.books;
--   drop function if exists public.books_preserve_takedown();
-- ==========================================================================

create or replace function public.books_preserve_takedown()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    -- دورا الـAPI وحدهما يُقيَّدان: `authenticated` دورُ كلِّ من يدخل من
    -- التطبيق (والزائرُ منهم)، و`anon` من لم يسجّل. وما عداهما — أنت من
    -- اللوحة، أو خادمٌ بمفتاح الخدمة — يمرّ كما هو.
    if current_user in ('authenticated', 'anon') then
        new.is_taken_down     := old.is_taken_down;
        new.taken_down_at     := old.taken_down_at;
        new.taken_down_reason := old.taken_down_reason;
    end if;
    return new;
end;
$$;

drop trigger if exists books_preserve_takedown on public.books;
create trigger books_preserve_takedown
    before update on public.books
    for each row execute function public.books_preserve_takedown();
