-- ==========================================================================
-- حذفُ الحساب يسحب ملفاتِ المخازن معه — شبكةُ أمان
-- ==========================================================================
-- التطبيق يمسح ملفات المعلّم من المخازن قبل أن ينادي هذه الدالّة
-- (`purgeStorage` في auth.js)، وذلك هو المسارُ الصحيح: يمرّ بواجهة التخزين
-- فيزول الملفُّ وسجلُّه معاً.
--
-- **لكنّه مسارٌ قد ينقطع.** المسحُ يجري على الشبكة، والحذفُ يمضي بعده ولو
-- فشل (وهو الصواب: ألّا يُحبس المعلّم في حسابٍ يريد حذفَه لأنّ شبكتَه
-- تعثّرت). وحين ينقطع تبقى الملفاتُ **إلى الأبد**: سياساتُ المخزن تُطابق
-- المجلّدَ بـ`auth.uid()`، والمعرّفُ صاحبُ المجلّد لم يعد له وجود — فلا
-- أحدَ يستطيع الوصولَ إليها ولا حذفَها، لا صاحبُها ولا غيرُه.
--
-- وآبل تشترط أن يحذف التطبيقُ بيانات المستخدم كلَّها لا صفوفَه وحدها
-- (App Store Guideline 5.1.1(v)).
--
-- فتُحذف السجلّاتُ هنا في المعاملة نفسِها التي تحذف الحساب: إن نجح مسحُ
-- التطبيق لم تجد هذه العبارةُ شيئاً، وإن فشل لم يبقَ للمعلّم سجلُّ ملفٍّ
-- واحد على الخادم.
--
-- ── حدُّها الذي يُقال صراحةً ──
-- حذفُ السجلّ من `storage.objects` يُخفي الملفَّ عن الواجهة ويُسقط بياناته،
-- **وقد تبقى نسخةُ الملفّ في التخزين الكائنيّ** لأنّ ذلك لا يُنجَز إلّا عبر
-- واجهة التخزين لا بـSQL. فالمسارُ الأوّل (التطبيق) هو الذي يحذف حذفاً
-- تامّاً، وهذه شبكةٌ تحته لا بديلٌ عنه.
--
-- ── ولماذا الشرطُ بالمجلّد لا بعمود `owner` ──
-- `owner` يُملأ من الجلسة وقد يكون فارغاً في صفوفٍ قديمة، وقد يختلف اسمه
-- بين إصدارات Supabase — وخطأٌ في اسم عمودٍ داخل دالّةٍ كهذه لا يظهر عند
-- إنشائها بل **عند أوّل حذفِ حساب**. أمّا المجلّدُ فهو نظامُ المشروع نفسِه:
-- كلُّ ملفٍّ يسكن مجلّداً باسم معرّف صاحبه، وعليه تقوم سياساتُ المخازن
-- الثلاثة أصلاً — وهي تعمل.
--
-- ── الرجوع ──
-- تُعاد الدالّةُ بجسمها السابق (حذفُ `auth.users` وحده) من ترحيل
-- 20260809100000_delete_own_account.sql.
-- ==========================================================================

create or replace function public.delete_own_account()
returns void
language plpgsql
security definer
set search_path = auth, public
as $$
declare
    uid uuid := auth.uid();
begin
    -- auth.uid() هو الضمانة: لا يستطيع المستخدم حذف غير نفسه مهما استُدعيت.
    if uid is null then
        raise exception 'not authenticated';
    end if;

    -- المخازنُ الثلاثةُ بالاسم لا غير: الشرطُ محصورٌ فلا يطال شيئاً آخر
    -- مهما تغيّر المشروع.
    delete from storage.objects
     where bucket_id in ('books', 'evidence', 'portfolio')
       and (storage.foldername(name))[1] = uid::text;

    delete from auth.users where id = uid;
end;
$$;

-- الصلاحيّاتُ كما كانت: للمسجَّلين وحدهم، لا للزائر غير المسجَّل.
revoke all     on function public.delete_own_account() from public, anon;
grant  execute on function public.delete_own_account() to authenticated;
