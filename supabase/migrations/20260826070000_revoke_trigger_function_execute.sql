-- دوالُّ المُشغِّلات تُنشأ بصلاحيّة تنفيذٍ ممنوحةٍ لـ`PUBLIC` افتراضاً، فتظهر
-- في التدقيق كأنّها أبوابٌ مفتوحة. وهي ليست كذلك: PostgREST لا يكشف دالّةً
-- تُرجع `trigger` إطلاقاً — جُرّبت الأربعُ فردّت `404`.
--
-- والسحبُ تنظيفٌ لا إصلاح. **والسؤال الذي لا أعرف جوابه يقيناً:** أيفحص
-- بوستجرس هذي الصلاحيّة عند **إطلاق** المُشغِّل أم عند **إنشائه** فقط؟ لو
-- كان الأوّل، لتعطّل كلُّ تعديلٍ على `books` من التطبيق.
--
-- فتُجرَّب على دالّةٍ واحدةٍ أقلِّها أثراً — سجلُّ الإنزال — ويُقاس:
-- معلّمٌ يعدّل عنوان كتابه، فيُطلق المُشغِّلَ بدور `authenticated`.
--   • نجح التعديل ← الفحصُ عند الإنشاء لا الإطلاق، فالسحبُ آمنٌ للبقيّة.
--   • فشل        ← يُعاد في الحال، ولا تُمسّ الثلاثُ الأخرى.
--
-- ── الرجوع ──
--   grant execute on function public.log_book_takedown() to public;
-- ==========================================================================

revoke execute on function public.log_book_takedown() from public, anon, authenticated;
