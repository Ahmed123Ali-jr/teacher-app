-- ==========================================================================
-- إقفالُ مخزن الكتب — بابٌ لم يعد التطبيقُ يطرقه
-- ==========================================================================
-- كانت الكتبُ تُرفع إلى مخزن `books`، ثمّ صارت تُحفظ على جهاز المعلّم وحده
-- (قرارُ المستخدم، ١٢ مايو ٢٠٢٦). فكلُّ كتابٍ يُضاف اليوم يُكتب في صفّه
-- `storage_path = 'local'` والملفُّ في IndexedDB — **ولا بايتَ يصعد**.
--
-- وبقي المخزنُ ببابه مفتوحاً: أيُّ حسابٍ مسجَّلٍ يرفع فيه ملفاتٍ حتى ٢٥٠
-- ميجابايت للملفّ الواحد. **والحسابُ يُصنع بضغطة زائرٍ واحدة بلا بريدٍ ولا
-- كلمة مرور** — فأربعةُ ملفاتٍ تملأ الجيجابايت المجانيّ كلَّه، ويتوقّف رفعُ
-- الشواهد وملفّات الإنجاز على المعلّمين الحقيقيّين.
--
-- فتُسقط سياساتُه الأربع: لا رفعَ ولا قراءةَ ولا تعديلَ ولا حذف — لأحد.
--
-- **وقرّر المستخدم حذفَ المخزن نهائياً بما فيه** (٢٦ أغسطس ٢٠٢٦): «لا
-- أحتاجها وتُعتبر ثغرة». وحذفُ المحتوى لا يتمّ بـSQL — سوبابيس تمنع الحذفَ
-- المباشر من جداول التخزين — فيُنجَز من لوحة التحكّم، وهذا الترحيلُ يُقفل
-- البابَ حتى يُنجَز.
--
-- ── ما يفقده المعلّم ──
-- كتابٌ رُفع قبل ١٢ مايو ولم يعد على جهازه: لن يُفتح. وقرارُ المستخدم صريح.
-- ورسالةُ القارئ تقول له الصواب: «الملف غير محفوظ على هذا الجهاز — افتحه من
-- الجهاز الذي رُفع منه، أو أعد رفعه».
--
-- ── الرجوع ──
-- تُعاد السياساتُ الأربع من 20260512200000_books_storage_bucket.sql.
-- ==========================================================================

drop policy if exists "books_owner_read"   on storage.objects;
drop policy if exists "books_owner_insert" on storage.objects;
drop policy if exists "books_owner_update" on storage.objects;
drop policy if exists "books_owner_delete" on storage.objects;
