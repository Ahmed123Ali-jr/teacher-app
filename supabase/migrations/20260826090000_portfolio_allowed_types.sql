-- ==========================================================================
-- قائمةُ ما يُقبل في مخزن ملفّ الإنجاز — والصيغةُ المخادعة تُردّ
-- ==========================================================================
-- المخزنُ كان يقبل **أيّ نوعِ ملفّ** (`allowed_mime_types = null`). وأكثرُ
-- ما يُرفع فيه لا يضرّ: HTML وXML تُخدَمان `text/plain` — سوبابيس تُبطلهما
-- من تلقائها. **إلّا SVG: يُخدَم `image/svg+xml`**، فمن فتح رابطَه الموقّع
-- عمل ما فيه من شيفرة.
--
-- وأثرُه محدود: على نطاق سوبابيس لا نطاق التطبيق، والتطبيقُ يعرض المرفقات
-- في `<img>` فلا تُنفَّذ. فهي استضافةُ محتوىً لا اختراقُ حساب. لكنّه بابٌ
-- بلا فائدة، ويُغلق بلا ثمن.
--
-- ── ولماذا `application/octet-stream` في القائمة ──
-- **هو الذي يمنع تكرار عطبٍ وقع من قبل.** قيدُ الأنواع رُفع عن مخزن الكتب
-- يوم ٢٠٢٦٠٥١٢ لأنّ iOS يرسل الـPDF أحياناً بنوعٍ فارغ أو
-- `application/octet-stream`، فكان الرفعُ يُردّ بلا سبب يفهمه المعلّم.
--
-- **ولا يُبطل الحماية**: الملفُّ الذي يصل بهذا النوع **يُخدَم به**، فيُنزَّل
-- على جهاز من يفتحه ولا يُفتح صفحةً — فلو أرسل أحدٌ صيغتَه المخادعة تحت
-- هذا الاسم، مرّت ميّتةً لا تعمل. فالبابُ مغلقٌ من الجهتين: بالاسم الصريح
-- يُردّ عند الرفع، وبالاسم المستعار يمرّ بلا أثر.
--
-- ── وHEIC/HEIF وGIF ──
-- صورُ الآيفون تصل `image/heic`، والضغطُ في المتصفّح يحوّلها JPEG **إلّا
-- الصغيرة منها** (أقلّ من ٣٠٠ كيلو لا تستحقّ ضغطاً) فتصل بنوعها. وGIF
-- يمرّ اليوم ولا خطر فيه، فلا يُحدَث رفضٌ جديد بلا داعٍ.
--
-- ── ما قد يُردّ بعد اليوم ولم يكن يُردّ ──
-- صيغُ صورٍ نادرة (TIFF، BMP) من ماسحٍ ضوئيّ قديم. واحتمالُها ضعيف،
-- والضغطُ يحوّل أكثرها قبل الرفع.
--
-- ── الرجوع ──
--   update storage.buckets set allowed_mime_types = null where id = 'portfolio';
-- ==========================================================================

update storage.buckets
   set allowed_mime_types = array[
        'application/pdf',
        'image/jpeg',
        'image/png',
        'image/webp',
        'image/gif',
        'image/heic',
        'image/heif',
        'application/octet-stream'
   ]
 where id = 'portfolio';
