-- ============================================================================
--  الكشفُ المشترك — فصلان لنفس الشعبة بمادّتين يقرآن الطلابَ أنفسَهم
-- ============================================================================
--  المشكلة: «المادّة» جزءٌ من هويّة الفصل، فـ«أوّل متوسط/أ — علوم» و
--  «أوّل متوسط/أ — اجتماعيات» صفّان مختلفان في `classes`، والطالبُ يتبع
--  فصلاً واحداً (`students.class_id`). فيُدخل المعلّمُ الكشفَ نفسَه مرّتين،
--  ويُصحّح كلَّ اسمٍ مرّتين.
--
--  والحلُّ عمودٌ واحد: فصولٌ تحمل `roster_id` نفسَه **تقرأ الكشفَ نفسَه**.
--  ولا يُنقل صفُّ طالبٍ واحدٍ من مكانه — يتغيّر سؤالُ القراءة لا البيانات.
--
--  ── ولماذا يُقبل الفراغ ──
--  `NULL` تعني «كشفٌ خاصٌّ بهذا الفصل»، أي `roster = id`. فالفصولُ القائمةُ
--  كلُّها تبقى كما هي بلا تحديثٍ ولا هجرةِ بيانات، والتطبيقُ يقرأ
--  `coalesce(roster_id, id)`. ولو جُعل `not null` بقيمةٍ افتراضيّةٍ للزم
--  تحديثُ كلّ صفٍّ قائم، وبلا فائدة.
--
--  ── والحضورُ والدرجاتُ تبقى منفصلةً من نفسِها ──
--  لأنّها مربوطةٌ بـ`class_id` لا بالكشف. فطالبٌ حاضرٌ في العلوم غائبٌ في
--  الاجتماعيات — وهو الصواب: حصّتان مختلفتان.
--
--  ⚠️ وحفرةٌ يردمها التطبيقُ لا القاعدة: `students.class_id` عليها
--  `on delete cascade`. فحذفُ الفصل الذي تعلَّق به صفوفُ الطلاب يمحو الكشفَ
--  من شريكه. فالتطبيقُ ينقل الصفوفَ إلى الشريك الباقي **قبل** الحذف.
--  (`deleteClass` في `views/class.js`.)
-- ============================================================================

alter table public.classes
    add column if not exists roster_id uuid;

comment on column public.classes.roster_id is
    'الكشف المشترك: الفصول التي تحمل الرقم نفسه تقرأ الطلاب أنفسهم. NULL = كشف خاص بالفصل (roster = id).';

-- الفصولُ تُقرأ دائماً بمعلّمها، فالفهرسُ مركَّبٌ لا مفردٌ على العمود.
create index if not exists classes_teacher_roster_idx
    on public.classes (teacher_id, roster_id);
