/* ==========================================================================
   edu-departments.js — إدارات التعليم مرتّبة على المناطق الثلاث عشرة.

   المعلم يختار منطقته ثم إدارته بضغطتين — لا يكتب حرفاً، فلا يقع اختلاف في
   الإملاء بين معلّم وآخر ويبقى الاسم موحّداً في كل المطبوعات.

   المناطق الثلاث عشرة مؤكّدة. أما إدارات المحافظات فقائمة أولية تحتاج
   مراجعة المستخدم — إضافة إدارة ناقصة سطرٌ واحد هنا.
   ========================================================================== */

(function (global) {
    'use strict';

    const DATA = [
        { region: 'الرياض', depts: [
            'الرياض', 'الخرج', 'الدوادمي', 'المجمعة', 'الزلفي', 'شقراء',
            'الأفلاج', 'وادي الدواسر', 'القويعية', 'حوطة بني تميم', 'عفيف', 'السليل'
        ]},
        { region: 'مكة المكرمة', depts: [
            'مكة المكرمة', 'جدة', 'الطائف', 'القنفذة', 'الليث', 'رابغ'
        ]},
        { region: 'المدينة المنورة', depts: [
            'المدينة المنورة', 'ينبع', 'العلا'
        ]},
        { region: 'القصيم', depts: [
            'القصيم', 'الرس', 'عنيزة'
        ]},
        { region: 'الشرقية', depts: [
            'الشرقية', 'الأحساء', 'حفر الباطن', 'الجبيل', 'القطيف', 'الخفجي'
        ]},
        { region: 'عسير', depts: [
            'عسير', 'بيشة', 'النماص', 'محايل عسير', 'تثليث', 'ظهران الجنوب'
        ]},
        { region: 'تبوك',              depts: ['تبوك'] },
        { region: 'حائل',              depts: ['حائل'] },
        { region: 'الحدود الشمالية',   depts: ['الحدود الشمالية'] },
        { region: 'جازان',             depts: ['جازان', 'صبيا'] },
        { region: 'نجران',             depts: ['نجران', 'شرورة'] },
        { region: 'الباحة',            depts: ['الباحة', 'بلجرشي'] },
        { region: 'الجوف',             depts: ['الجوف', 'القريات'] }
    ];

    /** الاسم كما يُكتب في المطبوعات: «إدارة تعليم عسير». */
    function fullName(dept) {
        return dept ? 'إدارة تعليم ' + dept : '';
    }

    function regions() { return DATA.map((r) => r.region); }

    function of(region) {
        const hit = DATA.find((r) => r.region === region);
        return hit ? hit.depts.slice() : [];
    }

    /** المنطقة التي تتبعها إدارة محفوظة — لفتح المنتقي على اختيار المعلم. */
    function regionOf(dept) {
        const bare = String(dept || '').replace(/^\s*إدارة تعليم\s+/, '').trim();
        const hit = DATA.find((r) => r.depts.includes(bare));
        return hit ? hit.region : null;
    }

    /** الجزء المجرّد من اسم محفوظ: «إدارة تعليم عسير» → «عسير». */
    function bareName(dept) {
        return String(dept || '').replace(/^\s*إدارة تعليم\s+/, '').trim();
    }

    global.EduDepts = { regions, of, regionOf, fullName, bareName };
})(window);
