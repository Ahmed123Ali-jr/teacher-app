/* ==========================================================================
   period-times.js — أوقاتُ الحصص: مصدرٌ واحدٌ يقرأ منه الجميع.
   ==========================================================================
   كانت الأوقاتُ تُقرأ من `Settings.get('period_times')` مباشرةً في أربعة
   مواضع، ومن لم يفتح محرّرَ التوقيت قطُّ لا يملك هذا الرمز — فيرى الجدولَ
   بأوقاتٍ (لأنّ شاشته تُكمل بالافتراضيّ) وبقيّةَ التطبيق بلا أوقاتٍ أصلاً:

     • **الجرسُ يخرج صامتاً**: يُفعّله المعلّم في الإعدادات فلا يرنّ أبداً،
       ولا كلمةَ تقول لماذا. وهي أوّلُ ميزةٍ يجرّبها من يفتح التطبيق.
     • والرئيسيةُ بلا علامةٍ على أيّ حصّة.
     • وملفُّ الإنجاز يُطبع بجدولٍ بلا أوقات.

   وكان الإصلاحُ قد وقع مرّةً — لشاشةٍ واحدة، بتصدير `getPeriodTimes` من
   شاشة الجدول. لكنّ شاشةَ الجدول تُحمَّل عند فتحها وحدها، والجرسُ يعمل
   قبلها وبعدها. فالمصدرُ الموحّد يجب أن يكون هنا: مُحمَّلٌ دائماً، لا
   شاشةً تُنتظر.
   ========================================================================== */

(function (global) {
    'use strict';

    /* سبعُ حصصٍ ثابتة: أيُّ بياناتٍ قديمةٍ بعددٍ مختلفٍ تُقصّ أو تُكمَّل. */
    const COUNT = 7;

    const DEFAULTS = [
        { n: 1, start: '07:00', end: '07:45' },
        { n: 2, start: '07:45', end: '08:30' },
        { n: 3, start: '08:30', end: '09:15' },
        { n: 4, start: '09:45', end: '10:30' },   // بعد الفسحة
        { n: 5, start: '10:30', end: '11:15' },
        { n: 6, start: '11:15', end: '12:00' },
        { n: 7, start: '12:00', end: '12:45' }
    ];

    /**
     * أوقاتُ الحصص السبع، مُكمَّلةً بالافتراضيّ.
     * **لا تُرجع فارغاً أبداً** — وهذا كلُّ الغرض.
     * @returns {Promise<Array<{n:number,start:string,end:string}>>}
     */
    async function get() {
        let stored = null;
        try {
            stored = await global.TeacherDB.Settings.get('period_times');
        } catch (e) {
            /* تعذّرت القراءة: الافتراضيُّ خيرٌ من صمتٍ لا يُفسَّر. */
        }
        const rows = Array.isArray(stored) && stored.length ? stored : DEFAULTS;
        return Array.from({ length: COUNT }, (_, i) => ({
            ...(rows[i] || DEFAULTS[i]), n: i + 1
        }));
    }

    /** هل ضبط المعلّمُ أوقاتَه بنفسه؟ — لمن أراد التمييز. */
    async function isCustom() {
        try {
            const stored = await global.TeacherDB.Settings.get('period_times');
            return Array.isArray(stored) && stored.length > 0;
        } catch (e) { return false; }
    }

    global.PeriodTimes = { get, isCustom, DEFAULTS, COUNT };
})(window);
