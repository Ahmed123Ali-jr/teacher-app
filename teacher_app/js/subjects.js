/* ==========================================================================
   subjects.js — المواد الدراسية: مصدرُ حقيقةٍ واحد.

   كانت القائمة منسوخةً في ثلاثة ملفات — التسجيل والرئيسية وشاشة الفصل —
   فأيّ مادةٍ تُضاف تُنسى في اثنين منها. وشاشة التهيئة كانت ستصير رابعاً.

   والتقسيم على المراحل مقصود: معلّم الابتدائي لا يعنيه أن يرى الفيزياء
   والكيمياء، ومعلّم الثانوي لا يبحث عن المهارات الحياتية بين ست عشرة مادة.
   ========================================================================== */

(function (global) {
    'use strict';

    /* القائمة الكاملة — تُستعمل حيث لا مرحلةَ معلومة (التهيئة، التعديل). */
    const ALL = [
        'القرآن الكريم', 'التربية الإسلامية', 'اللغة العربية', 'اللغة الإنجليزية',
        'الرياضيات', 'العلوم', 'الأحياء', 'الفيزياء', 'الكيمياء',
        'الاجتماعيات', 'التاريخ', 'الجغرافيا',
        'المهارات الرقمية', 'المهارات الحياتية والأسرية', 'التفكير الناقد',
        'الحاسب وتقنية المعلومات', 'التربية الفنية', 'التربية البدنية'
    ];

    const BY_STAGE = {
        primary: [
            'القرآن الكريم', 'التربية الإسلامية', 'اللغة العربية', 'الرياضيات',
            'العلوم', 'الاجتماعيات', 'اللغة الإنجليزية',
            'المهارات الرقمية', 'المهارات الحياتية والأسرية',
            'التربية الفنية', 'التربية البدنية'
        ],
        intermediate: [
            'القرآن الكريم', 'التربية الإسلامية', 'اللغة العربية', 'الرياضيات',
            'العلوم', 'الاجتماعيات', 'اللغة الإنجليزية',
            'المهارات الرقمية', 'المهارات الحياتية والأسرية',
            'التربية الفنية', 'التربية البدنية'
        ],
        secondary: [
            'التربية الإسلامية', 'اللغة العربية', 'الرياضيات',
            'الفيزياء', 'الكيمياء', 'الأحياء', 'اللغة الإنجليزية',
            'التاريخ', 'الجغرافيا', 'الحاسب وتقنية المعلومات',
            'التفكير الناقد', 'التربية البدنية'
        ]
    };

    /** مواد المعلّم كما اختارها، وإلا مادته المفردة القديمة. */
    function ofTeacher(teacher) {
        if (!teacher) return [];
        if (Array.isArray(teacher.subjects) && teacher.subjects.length) return teacher.subjects;
        return teacher.subject ? [teacher.subject] : [];
    }

    /** مواد مرحلةٍ ما، وإلا الكلّ. */
    function ofStage(stage) {
        return BY_STAGE[stage] || ALL;
    }

    /** يدمج بلا تكرارٍ ولا فراغ — الترتيب يتبع أول ظهور. */
    function merge() {
        const out = [];
        for (const list of arguments) {
            (list || []).forEach((s) => {
                const v = String(s || '').trim();
                if (v && v !== 'أخرى' && out.indexOf(v) < 0) out.push(v);
            });
        }
        return out;
    }

    global.Subjects = { ALL, BY_STAGE, ofTeacher, ofStage, merge };
})(window);
